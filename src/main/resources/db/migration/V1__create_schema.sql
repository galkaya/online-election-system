-- Online Election System schema (H2). Managed by Flyway; Hibernate only validates it.
--
-- Note on the two value checks (role, status): they use REGEXP_LIKE instead of "column IN ('A', 'B')".
-- With H2 2.4.240, a CHECK that compares a VARCHAR column with string literals stops working as soon
-- as the connection that created the table is closed (error 23514, "database has been closed").
-- REGEXP_LIKE does not have that problem. RepositoryConstraintsIT covers both checks.

CREATE TABLE app_user (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(50)  NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    display_name  VARCHAR(100) NOT NULL,
    role          VARCHAR(20)  NOT NULL,
    enabled       BOOLEAN      NOT NULL,
    created_at    TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_app_user_username UNIQUE (username),
    CONSTRAINT ck_app_user_role CHECK (REGEXP_LIKE(role, '^(ADMIN|VOTER)$'))
);

CREATE TABLE election (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title       VARCHAR(120)  NOT NULL,
    description VARCHAR(1000) NOT NULL,
    starts_at   TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    ends_at     TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    status      VARCHAR(20)   NOT NULL,
    created_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_election_window CHECK (starts_at < ends_at),
    CONSTRAINT ck_election_status CHECK (REGEXP_LIKE(status, '^(DRAFT|OPEN|CLOSED)$'))
);

CREATE TABLE candidate (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    election_id BIGINT       NOT NULL,
    name        VARCHAR(100) NOT NULL,
    biography   VARCHAR(500) NOT NULL,
    CONSTRAINT fk_candidate_election FOREIGN KEY (election_id) REFERENCES election (id),
    CONSTRAINT uq_candidate_election_name UNIQUE (election_id, name),
    -- Target of the composite ballot foreign key: a ballot can only name a candidate of its own election.
    CONSTRAINT uq_candidate_id_election UNIQUE (id, election_id)
);

-- Who may vote in which election. Holds no candidate, ballot or receipt data.
CREATE TABLE election_eligibility (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    election_id BIGINT  NOT NULL,
    voter_id    BIGINT  NOT NULL,
    active      BOOLEAN NOT NULL,
    CONSTRAINT fk_eligibility_election FOREIGN KEY (election_id) REFERENCES election (id),
    CONSTRAINT fk_eligibility_voter FOREIGN KEY (voter_id) REFERENCES app_user (id),
    CONSTRAINT uq_eligibility_election_voter UNIQUE (election_id, voter_id)
);

-- Who has voted in which election. Deliberately no timestamp, candidate, ballot id or receipt.
CREATE TABLE participation (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    election_id BIGINT NOT NULL,
    voter_id    BIGINT NOT NULL,
    CONSTRAINT fk_participation_election FOREIGN KEY (election_id) REFERENCES election (id),
    CONSTRAINT fk_participation_voter FOREIGN KEY (voter_id) REFERENCES app_user (id),
    -- The one-vote rule, enforced by the database.
    CONSTRAINT uq_participation_election_voter UNIQUE (election_id, voter_id)
);

-- What was chosen. Deliberately no voter, username, session, IP address or timestamp.
-- The primary key is a random UUID so that key order does not reveal insertion order.
CREATE TABLE ballot (
    id           UUID        NOT NULL PRIMARY KEY,
    election_id  BIGINT      NOT NULL,
    candidate_id BIGINT      NOT NULL,
    receipt_hash VARCHAR(64) NOT NULL,
    CONSTRAINT fk_ballot_election FOREIGN KEY (election_id) REFERENCES election (id),
    CONSTRAINT fk_ballot_candidate_of_election FOREIGN KEY (candidate_id, election_id)
        REFERENCES candidate (id, election_id),
    CONSTRAINT uq_ballot_receipt_hash UNIQUE (receipt_hash)
);

CREATE INDEX ix_ballot_election ON ballot (election_id);

-- Administrative events and rejected attempts. Never stores a candidate choice, ballot id or receipt.
CREATE TABLE audit_event (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    occurred_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    event_type  VARCHAR(40)  NOT NULL,
    actor       VARCHAR(50),
    election_id BIGINT,
    detail      VARCHAR(500) NOT NULL
);

CREATE INDEX ix_audit_event_occurred_at ON audit_event (occurred_at);
